#!/usr/bin/env bash
# Rewrite url to the transport (ssh/https) of the host repo's origin.
norm_url() {
  local u="$1" o
  o="$(git -C "${root:-.}" remote get-url origin 2>/dev/null)" || { printf '%s' "$u"; return 0; }
  if [[ "$o" == git@* || "$o" == ssh://* ]] && [[ "$u" =~ ^https?://([^/]+)/(.+)$ ]]; then
    printf 'git@%s:%s' "${BASH_REMATCH[1]}" "${BASH_REMATCH[2]}"
  elif [[ "$o" == http://* || "$o" == https://* ]] && [[ "$u" =~ ^git@([^:]+):(.+)$ ]]; then
    printf 'https://%s/%s' "${BASH_REMATCH[1]}" "${BASH_REMATCH[2]}"
  else
    printf '%s' "$u"
  fi
}
# .githooks/stack-sync.sh — clone missing stack repos from stacks.csv and keep
# the managed ignore block in .git/info/exclude (local, untracked) up to date.
# Idempotent: safe to run any number of times.
# NEVER touches tracked files (a dirty tree would abort the next `git pull`
# and the hook would never fire), never pulls/pushes inside stack repos and
# never deletes anything. stacks.md is regenerated by the pre-commit hook only.
#
# Env overrides (used by tests): STACKS_ROOT, STACKS_MANIFEST, STACKS_EXCLUDE
set -euo pipefail

ROOT="${STACKS_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
MANIFEST="${STACKS_MANIFEST:-$ROOT/stacks.csv}"
BEGIN_MARK="# BEGIN stack-sync (generated - do not edit)"
END_MARK="# END stack-sync"

cd "$ROOT"

EXCLUDE="${STACKS_EXCLUDE:-}"
if [[ -z "$EXCLUDE" ]]; then
  EXCLUDE="$(git rev-parse --path-format=absolute --git-path info/exclude 2>/dev/null || true)"
fi

if [[ ! -f "$MANIFEST" ]]; then
  echo "stack-sync: manifest not found: $MANIFEST" >&2
  exit 1
fi

# --- 1. clone missing repos ------------------------------------------------
while IFS=';' read -r path url status; do
  path="${path%$'\r'}"
  [[ -z "$path" || "$path" == \#* || "$path" == "path" ]] && continue
  url="${url%$'\r'}"
  if [[ -z "$url" || "$url" == "-" ]]; then
    echo "stack-sync: WARN no url for '$path', skipping" >&2
    continue
  fi
  if [[ -e "$path/.git" ]]; then
    continue  # already a repo — nothing to do
  fi
  if [[ -e "$path" && ! -d "$path" ]]; then
    echo "stack-sync: WARN '$path' exists and is not a directory, skipping" >&2
    continue
  fi
  if [[ -d "$path" && -n "$(ls -A "$path")" ]]; then
    echo "stack-sync: WARN '$path' is a non-empty directory without .git, skipping" >&2
    continue
  fi
  mkdir -p "$(dirname "$path")"
  if ! git clone --quiet "$(norm_url "$url")" "$path" < /dev/null; then
    echo "stack-sync: WARN clone failed for '$path' ($url)" >&2
  fi
done < "$MANIFEST"

# --- 2. managed ignore block in .git/info/exclude ----------------------------
[[ -z "$EXCLUDE" ]] && exit 0
mkdir -p "$(dirname "$EXCLUDE")"
block_file="$(mktemp)"
new_file="$(mktemp)"
trap 'rm -f "$block_file" "$new_file"' EXIT
{
  printf '%s\n' "$BEGIN_MARK"
  awk -F';' '{ sub(/\r$/, "", $1) } $1 != "" && $1 !~ /^#/ && $1 != "path" { print $1 "/" }' "$MANIFEST" | LC_ALL=C sort -u
  printf '%s\n' "$END_MARK"
} > "$block_file"

if [[ -f "$EXCLUDE" ]] && grep -qF "$BEGIN_MARK" "$EXCLUDE"; then
  awk -v block="$block_file" '
    BEGIN { n = 0; while ((getline l < block) > 0) B[n++] = l; close(block) }
    $0 == B[0] { for (i = 0; i < n; i++) print B[i]; inblk = 1; next }
    inblk && $0 == B[n-1] { inblk = 0; next }
    !inblk { print }
  ' "$EXCLUDE" > "$new_file"
elif [[ -f "$EXCLUDE" ]]; then
  { cat "$EXCLUDE"; cat "$block_file"; } > "$new_file"
else
  cp "$block_file" "$new_file"
fi
if ! cmp -s "$new_file" "$EXCLUDE" 2>/dev/null; then
  cat "$new_file" > "$EXCLUDE"
fi
